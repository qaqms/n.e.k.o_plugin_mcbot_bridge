# Copy edits made in the N.E.K.O. source tree back into this standalone
# repository, then verify nothing drifted.
#
# Pair with sync-in.ps1: that one pushes the repository into the host tree so
# you can test; this one pulls the result back so the tested code is what you
# commit. Repository-only files (.git, .github, .vscode, ruff.toml,
# pyproject.toml, tests/) are never touched.

[CmdletBinding()]
param(
    [string]$RepoDir = $PSScriptRoot,
    [string]$NekoRoot = "E:\NEKOdm\N.E.K.O",
    [switch]$Check
)

$ErrorActionPreference = "Stop"

$pluginId = "mcbot_bridge"
$source = Join-Path (Join-Path $NekoRoot "plugin\plugins") $pluginId

$items = @(
    "__init__.py",
    "client.py",
    "service.py",
    "prompts.py",
    "plugin.toml",
    "config.schema.json",
    "README.md",
    "i18n"
)

if (-not (Test-Path (Join-Path $source "plugin.toml"))) {
    throw "no plugin.toml in '$source' — nothing has been synced into the host tree yet"
}

$drift = @()
foreach ($item in $items) {
    $from = Join-Path $source $item
    $to = Join-Path $RepoDir $item
    if (-not (Test-Path $from)) {
        Write-Warning "host tree is missing: $item"
        continue
    }
    if ($Check) {
        if (-not (Test-Path $to)) {
            $drift += $item
            continue
        }
        if ((Get-FileHash -Algorithm SHA256 $from).Hash -ne (Get-FileHash -Algorithm SHA256 $to).Hash) {
            $drift += $item
        }
        continue
    }
    Copy-Item -Path $from -Destination $to -Recurse -Force
    Write-Host "  <- $item"
}

# plugin.meta.json is intentionally not round-tripped: it is regenerated by
# sync-in.ps1 from whatever tree it sits in, so copying it back would just add
# a stale artifact to the repository.

if ($Check) {
    if ($drift.Count -gt 0) {
        Write-Host ""
        Write-Host "Drift detected in: $($drift -join ', ')"
        Write-Host "Run sync-out.ps1 without -Check to pull the host-tree edits back."
        exit 1
    }
    Write-Host "No drift: the repository matches the host tree."
    exit 0
}

Write-Host ""
Write-Host "Pulled host-tree edits back into $RepoDir"
Write-Host "Review with 'git diff' before committing."
